-- Dimensión de eventos: tabla central para relacionar por event_id.
-- Las fechas de evento se guardan como hora local de Bolivia (timestamp sin zona).
CREATE VIEW powerbi.v_dim_evento AS
SELECT
  e.id                                         AS event_id,
  e.nombre                                     AS evento,
  te.nombre                                    AS tipo_evento,
  c.nombre                                     AS campana,
  e.ciudad,
  e.lugar,
  e.estado::text                               AS estado,
  e.fecha_inicio AT TIME ZONE 'America/La_Paz' AS fecha_inicio,
  e.fecha_fin    AT TIME ZONE 'America/La_Paz' AS fecha_fin,
  e.participantes_esperados,
  e.presupuesto
FROM public.evento e
JOIN public.tipo_evento te ON te.id = e.tipo_evento_id
LEFT JOIN public.campana c ON c.id = e.campana_id;

-- Mismas columnas y cifras que public.v_event_kpis + conteos para medidas DAX
-- que agregan bien entre varios eventos (NPS y satisfacción ponderados).
CREATE VIEW powerbi.v_event_kpis AS
SELECT
  k.*,
  COALESCE(n.respuestas_nps, 0)          AS respuestas_nps,
  COALESCE(n.promotores, 0)              AS promotores,
  COALESCE(n.detractores, 0)             AS detractores,
  COALESCE(n.respuestas_satisfaccion, 0) AS respuestas_satisfaccion,
  COALESCE(n.suma_satisfaccion, 0)       AS suma_satisfaccion
FROM powerbi.fn_event_kpis() k
LEFT JOIN (
  SELECT
    r.evento_id,
    count(s.nps)                        AS respuestas_nps,
    count(*) FILTER (WHERE s.nps >= 9)  AS promotores,
    count(*) FILTER (WHERE s.nps <= 6)  AS detractores,
    count(s.general)                    AS respuestas_satisfaccion,
    sum(s.general)                      AS suma_satisfaccion
  FROM public.surveys s
  JOIN public.registro_asistido r ON r.id = s.registro_id
  GROUP BY r.evento_id
) n ON n.evento_id = k.evento_id;

-- Audiencia agregada (sin usuario_id, nombre ni apellido). Ciudad y rango de
-- edad solo de personas que dieron consentimiento en algún registro; el resto
-- se agrupa como "Sin consentimiento".
CREATE VIEW powerbi.v_participant_type AS
WITH consentimiento AS (
  SELECT usuario_id, bool_or(consentimiento) AS consentimiento
  FROM public.registro_asistido
  GROUP BY usuario_id
)
SELECT
  p.tipo_participante,
  CASE WHEN c.consentimiento THEN COALESCE(p.rango_edad::text, 'Sin dato') ELSE 'Sin consentimiento' END AS rango_edad,
  CASE WHEN c.consentimiento THEN COALESCE(p.ciudad, 'Sin dato')           ELSE 'Sin consentimiento' END AS ciudad,
  count(*)                   AS personas,
  sum(p.eventos_registrados) AS eventos_registrados,
  sum(p.eventos_asistidos)   AS eventos_asistidos
FROM powerbi.fn_participant_type() p
JOIN consentimiento c ON c.usuario_id = p.usuario_id
GROUP BY 1, 2, 3;

CREATE VIEW powerbi.v_product_interest     AS SELECT * FROM powerbi.fn_product_interest();
CREATE VIEW powerbi.v_activity_performance AS SELECT * FROM powerbi.fn_activity_performance();
CREATE VIEW powerbi.v_hourly_traffic       AS SELECT * FROM powerbi.fn_hourly_traffic();
CREATE VIEW powerbi.v_funnel_levels        AS SELECT * FROM powerbi.fn_funnel_levels();
CREATE VIEW powerbi.v_city_map             AS SELECT * FROM powerbi.fn_city_map();
CREATE VIEW powerbi.v_recurrence           AS SELECT * FROM powerbi.fn_recurrence();

CREATE VIEW powerbi.v_report_historial AS
SELECT report_run_id, event_id, evento_nombre, tipo_reporte, formato, generado_por,
       parametros::text AS parametros, eventos_incluidos, generated_at
FROM powerbi.fn_report_historial();

CREATE VIEW powerbi.v_report_snapshot            AS SELECT * FROM powerbi.fn_report_snapshot();
CREATE VIEW powerbi.v_report_comparacion_eventos AS SELECT * FROM powerbi.fn_report_comparacion_eventos();

-- ----------------------------------------------------------------------------
-- Rol de solo lectura para Power BI. La contraseña NO va en el repositorio:
--   ALTER ROLE powerbi_reader WITH PASSWORD '<contraseña>';   (ver powerbi/README_WINDOWS.md)
-- Sin contraseña el rol no puede iniciar sesión.
-- ----------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'powerbi_reader') THEN
    CREATE ROLE powerbi_reader LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 5;
  END IF;
END
$$;

ALTER ROLE powerbi_reader SET default_transaction_read_only = on;
ALTER ROLE powerbi_reader SET statement_timeout = '120s';
ALTER ROLE powerbi_reader SET search_path = powerbi;

-- Las vistas llaman a las funciones con el usuario conectado: necesita EXECUTE,
-- que solo devuelve lo mismo que ya muestran las vistas.
REVOKE ALL ON ALL TABLES    IN SCHEMA powerbi FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA powerbi FROM PUBLIC, anon, authenticated;
GRANT USAGE   ON SCHEMA powerbi TO powerbi_reader;
GRANT SELECT  ON ALL TABLES    IN SCHEMA powerbi TO powerbi_reader;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA powerbi TO powerbi_reader;
