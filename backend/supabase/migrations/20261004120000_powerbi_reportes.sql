-- ============================================================================
-- Coca-Cola Event Intelligence
-- Reportes persistidos + capa de solo lectura para Power BI.
--
-- 1. report_runs / report_snapshots: cada reporte generado o exportado desde
--    la app deja un registro y una foto de los KPIs de v_event_kpis.
-- 2. public.v_report_*: vistas que lee la app (service_role) para el historial.
-- 3. Esquema powerbi: copias de solo lectura de las vistas v_* sin datos
--    personales, accesibles únicamente por el rol powerbi_reader.
--
-- Solo agrega objetos; no modifica tablas ni vistas existentes.
-- Las vistas públicas existentes usan security_invoker (RLS para usuarios
-- autenticados), por eso Power BI no las lee directamente: las vistas del
-- esquema powerbi se ejecutan con los permisos de su dueño (postgres) y
-- exponen solo columnas agregadas o seudónimas.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Tablas
-- ----------------------------------------------------------------------------
CREATE TABLE public.report_runs (
  id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id      integer      REFERENCES public.evento (id) ON DELETE SET NULL,
  tipo_reporte  varchar(60)  NOT NULL,
  formato       varchar(4)   NOT NULL,
  parametros    jsonb        NOT NULL DEFAULT '{}'::jsonb,
  generado_por  varchar(120) NOT NULL DEFAULT 'sistema',
  generated_at  timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT chk_report_runs_formato CHECK (formato IN ('csv', 'pdf', 'xlsx')),
  CONSTRAINT chk_report_runs_parametros CHECK (jsonb_typeof(parametros) = 'object')
);

COMMENT ON TABLE public.report_runs IS
  'Cada reporte generado o exportado desde la app (event_id NULL = todos los eventos).';

CREATE INDEX idx_report_runs_generated_at ON public.report_runs (generated_at DESC);
CREATE INDEX idx_report_runs_event        ON public.report_runs (event_id);

CREATE TABLE public.report_snapshots (
  id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_run_id     bigint       NOT NULL REFERENCES public.report_runs (id) ON DELETE CASCADE,
  event_id          integer      REFERENCES public.evento (id) ON DELETE SET NULL,
  evento_nombre     varchar(120) NOT NULL,
  registrados       integer      NOT NULL DEFAULT 0,
  asistentes        integer      NOT NULL DEFAULT 0,
  pct_asistencia    numeric,
  interacciones     integer      NOT NULL DEFAULT 0,
  muestras          integer      NOT NULL DEFAULT 0,
  pct_participacion numeric,
  consentimientos   integer      NOT NULL DEFAULT 0,
  conversiones      integer      NOT NULL DEFAULT 0,
  tasa_conversion   numeric,
  canjes            integer      NOT NULL DEFAULT 0,
  satisfaccion      numeric,
  nps               numeric,
  recurrencia       numeric,
  generated_at      timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT uq_report_snapshot_evento UNIQUE (report_run_id, event_id)
);

COMMENT ON TABLE public.report_snapshots IS
  'KPIs congelados de v_event_kpis en el momento de generar cada reporte.';
COMMENT ON COLUMN public.report_snapshots.muestras IS 'Degustaciones (log_activity de tipo degustacion).';
COMMENT ON COLUMN public.report_snapshots.recurrencia IS '% de asistentes con eventos previos.';

CREATE INDEX idx_report_snapshots_event ON public.report_snapshots (event_id);

-- Solo el servidor (service_role) escribe y lee estas tablas.
ALTER TABLE public.report_runs      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.report_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.report_runs, public.report_snapshots FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.report_runs, public.report_snapshots TO service_role;

-- ----------------------------------------------------------------------------
-- registrar_reporte: guarda el reporte y su snapshot en una sola transacción.
-- ----------------------------------------------------------------------------
CREATE FUNCTION public.registrar_reporte(
  p_event_id     integer,
  p_tipo_reporte text,
  p_formato      text,
  p_parametros   jsonb DEFAULT '{}'::jsonb,
  p_generado_por text  DEFAULT 'sistema'
) RETURNS bigint
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_run_id bigint;
BEGIN
  IF p_event_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM evento WHERE id = p_event_id) THEN
    RAISE EXCEPTION 'El evento % no existe', p_event_id USING ERRCODE = 'P0002';
  END IF;

  INSERT INTO report_runs (event_id, tipo_reporte, formato, parametros, generado_por)
  VALUES (p_event_id, p_tipo_reporte, p_formato, COALESCE(p_parametros, '{}'::jsonb), COALESCE(NULLIF(trim(p_generado_por), ''), 'sistema'))
  RETURNING id INTO v_run_id;

  INSERT INTO report_snapshots (
    report_run_id, event_id, evento_nombre, registrados, asistentes, pct_asistencia,
    interacciones, muestras, pct_participacion, consentimientos, conversiones,
    tasa_conversion, canjes, satisfaccion, nps, recurrencia, generated_at
  )
  SELECT
    v_run_id, k.evento_id, k.evento, k.registrados, k.asistentes, k.pct_asistencia,
    k.interacciones_producto, k.degustaciones, k.pct_participacion,
    k.registros_con_consentimiento, k.conversiones, k.tasa_conversion, k.canjes,
    k.satisfaccion, k.nps, k.pct_recurrencia, now()
  FROM v_event_kpis k
  WHERE p_event_id IS NULL OR k.evento_id = p_event_id;

  IF p_event_id IS NOT NULL AND NOT FOUND THEN
    RAISE EXCEPTION 'El evento % no existe', p_event_id USING ERRCODE = 'P0002';
  END IF;

  RETURN v_run_id;
END;
$$;

COMMENT ON FUNCTION public.registrar_reporte(integer, text, text, jsonb, text) IS
  'Registra un reporte en report_runs y congela los KPIs de v_event_kpis en report_snapshots.';

REVOKE ALL ON FUNCTION public.registrar_reporte(integer, text, text, jsonb, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_reporte(integer, text, text, jsonb, text) TO service_role;

-- ----------------------------------------------------------------------------
-- Vistas de reportes (las lee la app con service_role)
-- ----------------------------------------------------------------------------
CREATE VIEW public.v_report_historial WITH (security_invoker = on) AS
SELECT
  r.id                                  AS report_run_id,
  r.event_id,
  COALESCE(e.nombre, CASE WHEN r.event_id IS NULL THEN 'Todos los eventos' ELSE 'Evento eliminado' END)::varchar(120) AS evento_nombre,
  r.tipo_reporte,
  r.formato,
  r.generado_por,
  r.parametros,
  (SELECT count(*) FROM public.report_snapshots s WHERE s.report_run_id = r.id) AS eventos_incluidos,
  r.generated_at
FROM public.report_runs r
LEFT JOIN public.evento e ON e.id = r.event_id;

COMMENT ON VIEW public.v_report_historial IS 'Historial de reportes generados (fecha, evento, tipo, formato, usuario).';

CREATE VIEW public.v_report_snapshot WITH (security_invoker = on) AS
SELECT
  s.id            AS snapshot_id,
  s.report_run_id,
  s.event_id,
  s.evento_nombre,
  r.tipo_reporte,
  r.formato,
  s.registrados,
  s.asistentes,
  s.pct_asistencia,
  s.interacciones,
  s.muestras,
  s.pct_participacion,
  s.consentimientos,
  s.conversiones,
  s.tasa_conversion,
  s.canjes,
  s.satisfaccion,
  s.nps,
  s.recurrencia,
  s.generated_at
FROM public.report_snapshots s
JOIN public.report_runs r ON r.id = s.report_run_id;

COMMENT ON VIEW public.v_report_snapshot IS 'KPIs congelados por reporte y evento.';

-- Evento A vs Evento B con las cifras vigentes de v_event_kpis.
CREATE VIEW public.v_report_comparacion_eventos WITH (security_invoker = on) AS
SELECT
  a.evento_id                                    AS event_id_a,
  a.evento                                       AS evento_a,
  b.evento_id                                    AS event_id_b,
  b.evento                                       AS evento_b,
  a.asistentes                                   AS asistentes_a,
  b.asistentes                                   AS asistentes_b,
  a.asistentes - b.asistentes                    AS dif_asistentes,
  a.interacciones_producto                       AS interacciones_a,
  b.interacciones_producto                       AS interacciones_b,
  a.interacciones_producto - b.interacciones_producto AS dif_interacciones,
  a.conversiones                                 AS conversiones_a,
  b.conversiones                                 AS conversiones_b,
  a.conversiones - b.conversiones                AS dif_conversiones,
  a.canjes                                       AS canjes_a,
  b.canjes                                       AS canjes_b,
  a.canjes - b.canjes                            AS dif_canjes,
  a.satisfaccion                                 AS satisfaccion_a,
  b.satisfaccion                                 AS satisfaccion_b,
  a.satisfaccion - b.satisfaccion                AS dif_satisfaccion
FROM public.v_event_kpis a
JOIN public.v_event_kpis b ON b.evento_id <> a.evento_id;

COMMENT ON VIEW public.v_report_comparacion_eventos IS
  'Comparación Evento A vs Evento B (todas las parejas): asistentes, interacciones, conversiones, canjes y satisfacción. dif_* = A - B.';

REVOKE ALL ON public.v_report_historial, public.v_report_snapshot, public.v_report_comparacion_eventos FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.v_report_historial, public.v_report_snapshot, public.v_report_comparacion_eventos TO service_role;

-- ============================================================================
-- Esquema powerbi: lo único que ve el rol de Power BI.
-- Sin nombres, apellidos, email, celular, password_hash, códigos QR ni cupones.
--
-- Las vistas públicas v_* usan security_invoker, que comprueba permisos con el
-- usuario conectado aunque se lean desde otra vista. Por eso cada vista se lee
-- mediante una función SECURITY DEFINER (dueño postgres) que devuelve exactamente
-- las mismas filas; así Power BI ve las mismas cifras que la app.
-- ============================================================================
CREATE SCHEMA powerbi;
COMMENT ON SCHEMA powerbi IS 'Vistas de solo lectura para Power BI (rol powerbi_reader).';
REVOKE ALL ON SCHEMA powerbi FROM PUBLIC;

